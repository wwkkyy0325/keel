use std::path::PathBuf;
use std::time::Duration;

use async_trait::async_trait;
use serde::Serialize;

use crate::cancel::CancelToken;
use crate::ids::{InteractionId, ToolCallId, TurnId};

/// What the kernel is asking the user.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InteractionKind {
    Clarify,
    Choice,
    PlanApproval,
    PermissionApproval,
    Escalation,
}

impl InteractionKind {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Clarify => "clarify",
            Self::Choice => "choice",
            Self::PlanApproval => "plan_approval",
            Self::PermissionApproval => "permission_approval",
            Self::Escalation => "escalation",
        }
    }
}

/// Policy applied when a host does not answer before the deadline.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OnTimeout {
    Block,
    DeferAndContinue,
    EndTurn,
    Fail,
}

impl OnTimeout {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Block => "block",
            Self::DeferAndContinue => "defer_and_continue",
            Self::EndTurn => "end_turn",
            Self::Fail => "fail",
        }
    }
}

/// How long and how many times the kernel waits for a user interaction.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct InteractionPolicy {
    pub timeout: Duration,
    pub on_timeout: OnTimeout,
    pub max_per_turn: u32,
}

impl Default for InteractionPolicy {
    fn default() -> Self {
        Self {
            timeout: Duration::from_secs(300),
            on_timeout: OnTimeout::DeferAndContinue,
            max_per_turn: 4,
        }
    }
}

/// One option rendered by the host.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InteractionOption {
    pub id: String,
    pub label: String,
    pub description: Option<String>,
}

impl InteractionOption {
    pub fn new(id: impl Into<String>, label: impl Into<String>) -> Self {
        Self {
            id: id.into(),
            label: label.into(),
            description: None,
        }
    }
}

/// Scope granted by an approval.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GrantScope {
    Once,
    PathPrefix { prefix: PathBuf, ttl: Duration },
    FullAutoSession { ttl: Duration },
}

/// A typed request for user input. Generated by the kernel, never by a domain
/// tool.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InteractionRequest {
    pub id: InteractionId,
    pub turn_id: TurnId,
    pub kind: InteractionKind,
    pub prompt: String,
    pub options: Vec<InteractionOption>,
    /// Id of the option the model recommends, when it has one. Hosts mark it
    /// so the answer is one click rather than a read of every label.
    pub recommended: Option<String>,
    pub timeout_ms: Option<u64>,
    pub correlation: Option<ToolCallId>,
    /// Path the permission request applies to, when the request has one. Hosts
    /// use it to offer a path-scoped grant.
    pub path: Option<PathBuf>,
}

impl InteractionRequest {
    pub fn new(turn_id: TurnId, kind: InteractionKind, prompt: impl Into<String>) -> Self {
        Self {
            id: InteractionId::next(),
            turn_id,
            kind,
            prompt: prompt.into(),
            options: Vec::new(),
            recommended: None,
            timeout_ms: None,
            correlation: None,
            path: None,
        }
    }

    pub fn with_options(mut self, options: Vec<InteractionOption>) -> Self {
        self.options = options;
        self
    }
}

/// User answer to an interaction.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum InteractionResponse {
    Approved { scope: GrantScope },
    Rejected { reason: String },
    Selected { option: String },
    Freeform { text: String },
    Deferred,
    Cancelled,
    TimedOut,
}

impl InteractionResponse {
    pub fn outcome(&self) -> InteractionOutcome {
        match self {
            Self::Approved { .. } => InteractionOutcome::Approved,
            Self::Rejected { .. } => InteractionOutcome::Rejected,
            Self::Selected { .. } | Self::Freeform { .. } => InteractionOutcome::Approved,
            Self::Deferred => InteractionOutcome::Deferred,
            Self::Cancelled => InteractionOutcome::Cancelled,
            Self::TimedOut => InteractionOutcome::TimedOut,
        }
    }
}

/// Coarse outcome recorded in the event log.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum InteractionOutcome {
    Approved,
    Rejected,
    Deferred,
    Cancelled,
    TimedOut,
}

impl InteractionOutcome {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Approved => "approved",
            Self::Rejected => "rejected",
            Self::Deferred => "deferred",
            Self::Cancelled => "cancelled",
            Self::TimedOut => "timed_out",
        }
    }
}

/// Host port for user interaction. The kernel never knows the UI.
#[async_trait]
pub trait InteractionPort: Send + Sync {
    async fn request(
        &self,
        request: InteractionRequest,
        cancel: &CancelToken,
    ) -> InteractionResponse;
}
